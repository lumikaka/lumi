export function localizedErrorPresentation(t, error, options = {}) {
  const status = Number(error?.status) || 0
  const code = typeof error?.code === 'string' && error.code ? error.code : ''
  let messageKey = options.messageKey || ''
  if (!messageKey && ERROR_CODE_KEYS[code]) messageKey = ERROR_CODE_KEYS[code]
  if (!messageKey) {
    if (status === 0 && error && !code) messageKey = 'errors.network'
    else if (status === 401) messageKey = 'errors.unauthorized'
    else if (status === 403) messageKey = 'errors.forbidden'
    else if (status === 404) messageKey = 'errors.not_found'
    else if (status === 409) messageKey = 'errors.conflict'
    else if (status === 400 || status === 422) messageKey = 'errors.validation'
    else if (status >= 500) messageKey = 'errors.server'
    else messageKey = 'errors.generic'
  }
  return {
    title: t(options.titleKey || 'errors.title'),
    message: t(messageKey),
    code,
    status,
    diagnostic: [error?.message, error?.details].filter(Boolean).join('\n'),
  }
}
